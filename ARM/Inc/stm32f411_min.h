#ifndef STM32F411_MIN_H
#define STM32F411_MIN_H
#include <stdint.h>
#define REG32(a) (*(volatile uint32_t *)(a))
#define APB1_BASE 0x40000000UL
#define APB2_BASE 0x40010000UL
#define AHB1_BASE 0x40020000UL
#define RCC_BASE (AHB1_BASE+0x3800UL)
#define GPIOA_BASE AHB1_BASE
#define GPIOB_BASE (AHB1_BASE+0x400UL)
#define USART1_BASE (APB2_BASE+0x1000UL)
#define I2C1_BASE (APB1_BASE+0x5400UL)
#define TIM2_BASE APB1_BASE
#define RCC_CR REG32(RCC_BASE)
#define RCC_PLLCFGR REG32(RCC_BASE+4)
#define RCC_CFGR REG32(RCC_BASE+8)
#define RCC_AHB1ENR REG32(RCC_BASE+0x30)
#define RCC_APB1ENR REG32(RCC_BASE+0x40)
#define RCC_APB2ENR REG32(RCC_BASE+0x44)
#define GPIO_MODER(b) REG32((b)+0x00)
#define GPIO_OTYPER(b) REG32((b)+0x04)
#define GPIO_OSPEEDR(b) REG32((b)+0x08)
#define GPIO_PUPDR(b) REG32((b)+0x0C)
#define GPIO_AFRL(b) REG32((b)+0x20)
#define GPIO_AFRH(b) REG32((b)+0x24)
#define USART_SR REG32(USART1_BASE)
#define USART_DR REG32(USART1_BASE+4)
#define USART_BRR REG32(USART1_BASE+8)
#define USART_CR1 REG32(USART1_BASE+0x0C)
#define USART_CR2 REG32(USART1_BASE+0x10)
#define USART_CR3 REG32(USART1_BASE+0x14)
#define I2C_CR1 REG32(I2C1_BASE)
#define I2C_CR2 REG32(I2C1_BASE+4)
#define I2C_DR REG32(I2C1_BASE+0x10)
#define I2C_SR1 REG32(I2C1_BASE+0x14)
#define I2C_SR2 REG32(I2C1_BASE+0x18)
#define I2C_CCR REG32(I2C1_BASE+0x1C)
#define I2C_TRISE REG32(I2C1_BASE+0x20)
#define TIM_CR1 REG32(TIM2_BASE)
#define TIM_DIER REG32(TIM2_BASE+0x0C)
#define TIM_SR REG32(TIM2_BASE+0x10)
#define TIM_EGR REG32(TIM2_BASE+0x14)
#define TIM_PSC REG32(TIM2_BASE+0x28)
#define TIM_ARR REG32(TIM2_BASE+0x2C)
#define NVIC_ISER0 REG32(0xE000E100UL)
#define FLASH_ACR REG32(0x40023C00UL)
static inline void cpu_wfi(void){__asm volatile("wfi");}
#endif
